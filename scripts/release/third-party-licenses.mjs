// Writes the third-party licence list for flick.exe from `cargo metadata` (offline; nothing is downloaded).
// Only crates that go into the program on x86_64 Windows: normal and build dependencies reachable from the desktop
// host, not dev-only ones; the project's own path crates are left out.
// Usage (repo root): node scripts/release/third-party-licenses.mjs <cargo> <output .md>
// CARGO_HOME must point at a cache that already holds the locked crates.
import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
const [cargo, out] = process.argv.slice(2); if (!cargo || !out) throw Error('usage: <cargo> <output .md>');
// The local cache is indexed under the mirror registry the host gate uses; the lock file's crates are the same.
const mirror = JSON.parse(execFileSync('git', ['show', 'HEAD:contracts/desktop-bootstrap-mirror-v1/MIRROR.json'], {encoding: 'utf8'})).cargoArguments;
const meta = JSON.parse(execFileSync(cargo, [...mirror, 'metadata', '--offline', '--locked', '--format-version', '1', '--filter-platform', 'x86_64-pc-windows-msvc',
  '--manifest-path', 'apps/water/host/Cargo.toml'], {encoding: 'utf8', maxBuffer: 256 << 20}));
const byId = new Map(meta.packages.map(p => [p.id, p])), nodes = new Map(meta.resolve.nodes.map(n => [n.id, n]));
const seen = new Set(), queue = [meta.resolve.root];
while (queue.length) {
  const id = queue.pop(); if (seen.has(id)) continue; seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) if (d.dep_kinds.some(k => k.kind !== 'dev')) queue.push(d.pkg);
}
const rows = [...seen].map(id => byId.get(id)).filter(p => p.source !== null)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, {numeric: true}));
const missing = rows.filter(p => !p.license && !p.license_file);
const counts = rows.reduce((m, p) => (m[p.license ?? 'see licence file'] = (m[p.license ?? 'see licence file'] ?? 0) + 1, m), {});
const md = ['# Third-party licences', '',
  `Crates built into \`flick.exe\` (x86_64 Windows), from \`Cargo.lock\` of \`apps/water/host\`: ${rows.length}. Generated by \`cargo metadata\`; each crate's own licence text ships with its source on crates.io.`, '',
  '## By licence', '', '| Licence | Crates |', '|---|---|', ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`), '',
  '## Crates', '', '| Crate | Version | Licence | Source |', '|---|---|---|---|',
  ...rows.map(p => `| ${p.name} | ${p.version} | ${p.license ?? 'see licence file'} | ${p.repository ?? ''} |`), ''];
writeFileSync(out, md.join('\n'));
console.log(`${rows.length} crates, ${Object.keys(counts).length} licence expressions, without licence field: ${missing.map(p => p.name).join(', ') || 'none'}`);
